// Bundles the MCP runtime (src/mcp/runtime.ts and the Assistant tools it reuses)
// into one ES module the Supabase edge function imports.
// Run after changing any Assistant tool: npm run build:mcp
import { build } from 'esbuild';

await build({
  entryPoints: ['src/mcp/runtime.ts'],
  outfile: 'supabase/functions/mcp/runtime.js',
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  external: ['node:*'],
  legalComments: 'none',
  banner: { js: '// @ts-nocheck\n// Generated by scripts/build-mcp.mjs from src/mcp/runtime.ts. Do not edit.' },
  logLevel: 'info',
});
